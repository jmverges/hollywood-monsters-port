#!/usr/bin/env python3
"""Install the fan English translation (ShinjiGR and A.P.$lasH, v1.0.0, 2012) for the port.

usage: english_patch.py <unpacked-patch-dir> <data-dir>

The patch was made for the 2002 FX CD edition: it replaces RESOURCE files (dialogue, object names, pictures)
and ships its own MONSTERS.EXE with translated verbs and menus. The port runs the code and data of the 2010
digital edition's MONSTERS.EXE, so the patch's executable cannot be used directly. This script writes
<data-dir>/en/ and leaves the Spanish files untouched:

  1. the patch's RESOURCE files that differ from the Spanish ones,
  2. hm_lang.tsv: the texts of the two executables paired up (verb table, verb bar, options menu).

The port starts in the language saved in hm_lang.txt (Spanish by default); the port's menu (F9, or X/Square
on a controller) switches (platform/win32/lang.c). Saved games work in both languages.
Voices stay in Spanish: choose "Text" or "Both" in the options so the English subtitles are shown.
"""
import os
import shutil
import sys

VERB_TABLE = 0x5e4068          # 2010 executable: 2 connectors of 6 bytes, then 8 verbs of 12 bytes


def pe_sections(data):
    import struct
    pe = struct.unpack_from('<I', data, 0x3c)[0]
    nsec, optsz = struct.unpack_from('<H', data, pe + 6)[0], struct.unpack_from('<H', data, pe + 20)[0]
    base = struct.unpack_from('<I', data, pe + 24 + 28)[0]
    out = []
    for i in range(nsec):
        _, vsize, va, rsize, rptr = struct.unpack_from('<8sIIII', data, pe + 24 + optsz + 40 * i)
        out.append((base + va, rptr, rsize))
    return out


def off_to_va(secs, off):
    for va, rptr, rsize in secs:
        if rptr <= off < rptr + rsize:
            return va + off - rptr
    raise ValueError('offset %#x not in a section' % off)


def va_to_off(secs, va):
    for sva, rptr, rsize in secs:
        if sva <= va < sva + rsize:
            return rptr + va - sva
    raise ValueError('address %#x not in a section' % va)


def strings_from(data, off, count):
    """count zero-terminated strings starting at off, skipping zero padding between them: [(offset, bytes)]"""
    out = []
    while len(out) < count:
        while data[off] == 0:
            off += 1
        end = data.index(b'\0', off)
        out.append((off, data[off:end]))
        off = end + 1
    return out


def find_sequence(data, first, second):
    """offset of string `first` whose next string is `second`"""
    k = data.find(first + b'\0')
    while k >= 0:
        if strings_from(data, k, 2)[1][1] == second:
            return k
        k = data.find(first + b'\0', k + 1)
    raise SystemExit('could not find %r followed by %r' % (first, second))


def esc(b):
    return ''.join(chr(c) if 0x20 <= c < 0x7f and c != 0x5c else '\\\\' if c == 0x5c else '\\x%02x' % c for c in b)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    patch, data = sys.argv[1:3]
    def find(d, name):
        hit = [f for f in os.listdir(d) if f.lower() == name.lower()]
        return os.path.join(d, hit[0]) if hit else None
    es_exe, en_exe = find(data, 'MONSTERS.EXE'), find(patch, 'MONSTERS.EXE')
    if not es_exe or not en_exe:
        sys.exit('MONSTERS.EXE missing in %s or %s' % (data, patch))
    es, en = open(es_exe, 'rb').read(), open(en_exe, 'rb').read()
    secs = pe_sections(es)
    dst = find(data, 'en') or os.path.join(data, 'en')
    os.makedirs(dst, exist_ok=True)

    replaced = 0
    for f in sorted(os.listdir(patch)):
        if f.upper().startswith('RESOURCE.'):
            src, orig = os.path.join(patch, f), find(data, f)
            if orig and open(src, 'rb').read() == open(orig, 'rb').read():
                continue
            shutil.copyfile(src, os.path.join(dst, f.upper()))
            replaced += 1

    lines = ['# Texts of the English fan translation for the 2010 MONSTERS.EXE (generated by english_patch.py)']
    pairs = []
    # verb table, indexed by the code: patched in place
    es_tab = strings_from(es, va_to_off(secs, VERB_TABLE), 10)
    en_tab = strings_from(en, find_sequence(en, b' with', b' to'), 10)
    for (off, a), (_, b) in zip(es_tab, en_tab):
        lines.append('@%08x\t%s' % (off_to_va(secs, off), esc(b)))
        pairs.append((a, b))
    # verb bar labels and options menu: used as texts by the code
    blocks = [(find_sequence(es, b'Dar', b'Cerrar'), find_sequence(en, b'Give', b'Close'), 7, b'Hablar', b'Talk to'),
              (find_sequence(es, b'Texto', b'Voz'), find_sequence(en, b'Text', b'Speech'), 31, b'1024 x 768', b'1024 x 768')]
    for es_off, en_off, n, es_last, en_last in blocks:
        a, b = strings_from(es, es_off, n), strings_from(en, en_off, n)
        if a[-1][1] != es_last or b[-1][1] != en_last:
            sys.exit('text blocks do not line up (%r / %r)' % (a[-1][1], b[-1][1]))
        pairs += [(x[1], y[1]) for x, y in zip(a, b)]
    seen = set()
    for a, b in pairs:
        if a != b and a not in seen:
            seen.add(a)
            lines.append('%s\t%s' % (esc(a), esc(b)))
    with open(os.path.join(dst, 'hm_lang.tsv'), 'w', encoding='ascii') as f:
        f.write('\n'.join(lines) + '\n')
    print('%s: %d RESOURCE files from the patch, %d table entries and %d texts in hm_lang.tsv'
          % (dst, replaced, len(es_tab), len(lines) - 1 - len(es_tab)))


if __name__ == '__main__':
    main()
